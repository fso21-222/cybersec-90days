# === ДЕНЬ 10: СПИСКИ СЛОВАРЕЙ (ЛУТ-СИСТЕМА RUST) ===

print("=== 🎒 СКАНИРОВАНИЕ БОЛЬШОГО ДЕРЕВЯННОГО СУНДУКА ===")

# Большой список [], внутри которого лежат предметы-словари {}
large_chest = [
    {"item": "Автомат АК-47", "count": 1, "status": "Заряжен"},
    {"item": "Бобовая граната", "count": 6, "status": "Взрывоопасно"},
    {"item": "МВК (Металл высокого качества)", "count": 150, "status": "Ресурс"}
]

# Цикл for по очереди заглядывает в каждый слот сундука
for slot in large_chest:
    print("[ЛУТ] Предмет: " + slot["item"])
    print("[INFO] Статус: " + slot["status"])
    
    # Количество — это число (Integer), обязательно оборачиваем в str()!
    print("[COUNT] Количество в стаке: " + str(slot["count"]))
    print("-" * 45) # Разделительная линия между слотами

print("=== 🚀 Весь лут успешно проверен и готов к рейду! ===")
